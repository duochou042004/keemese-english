// SessionStart hook (startup | resume | clear | compact): gives a blank-slate session the
// verified repository state + the handoff prompt, and flags inconsistencies.
// Output is plain text (added to context); keep it under ~9,000 chars (platform cap: 10,000).
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const MAX_CHARS = 9000;

function git(cwd, ...args) {
  try {
    return execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trimEnd(); // keep leading status columns
  } catch {
    return null;
  }
}

/** Pure part: builds the briefing from collected facts (unit-tested). */
export function buildBriefing({ source, branch, head, dirty, aheadBehind, progress, progressError, handoff, commitsSinceHandoff }) {
  const out = [];
  const warn = [];
  out.push('# Session briefing (generated by .claude/hooks/session-start.mjs from the repository, not from memory)');
  if (source === 'compact') {
    out.push('**The context was just compacted. Treat this as a forced handoff point:** run the `handoff` skill now, then tell the user to continue in a new session.');
  }
  out.push(`- Branch: \`${branch ?? '?'}\` @ ${head ?? '?'}`);
  if (aheadBehind) out.push(`- Versus upstream: ${aheadBehind}`);
  out.push(`- Uncommitted changes: ${dirty.length ? `${dirty.length} file(s): ${dirty.slice(0, 12).join(', ')}${dirty.length > 12 ? ', …' : ''}` : 'none'}`);

  if (progressError) {
    warn.push(`progress.json is unreadable (${progressError}): fix it before doing anything else.`);
  } else if (progress) {
    const ct = progress.current_task ?? {};
    const nt = progress.next_task ?? {};
    out.push(`- progress.json (last_updated ${progress.last_updated ?? '?'}): phase ${progress.current_phase ?? '?'}; current task ${ct.id ?? '?'} [${ct.status ?? '?'}]; next task ${nt.id ?? '?'} (${nt.packet ?? 'no packet'})${nt.requires ? `; requires: ${nt.requires}` : ''}`);
    if (Array.isArray(progress.blockers) && progress.blockers.length) out.push(`- Blockers: ${progress.blockers.join(' | ')}`);
    if (Array.isArray(progress.pending_owner_actions) && progress.pending_owner_actions.length) {
      out.push(`- Waiting on the Lead Coordinator: ${progress.pending_owner_actions.join(' | ')}`);
    }
    if (ct.status === 'in_progress' && ct.branch && branch && !String(ct.branch).startsWith(branch)) {
      warn.push(`progress.json says the current task is on \`${ct.branch}\`, but the checkout is \`${branch}\`.`);
    }
  }
  if (commitsSinceHandoff > 0 && !dirty.some((f) => f.endsWith('docs/handoff/next-session.md'))) {
    warn.push(`${commitsSinceHandoff} non-merge commit(s) landed after the last handoff update: the handoff may be stale. Check \`git log\` before trusting it.`);
  }
  if (warn.length) out.push('', '## Inconsistencies (resolve first; the repository wins over the docs)', ...warn.map((w) => `- ${w}`));

  out.push('', '## Handoff prompt (docs/handoff/next-session.md)', handoff ? handoff.trim() : '_missing: read progress.json and the next task packet instead_');
  out.push('', 'Resume protocol: docs/agents/handoff.md#resume-protocol-new-session. Verify before trusting: re-run the last recorded check if you will build on it.');

  let text = out.join('\n');
  if (text.length > MAX_CHARS) text = `${text.slice(0, MAX_CHARS - 80)}\n…(truncated; read docs/handoff/next-session.md)`;
  return text;
}

function main() {
  let input = {};
  try { input = JSON.parse(fs.readFileSync(0, 'utf8') || '{}'); } catch { /* ignore */ }
  const dir = process.env.CLAUDE_PROJECT_DIR || input.cwd || process.cwd();

  let progress = null, progressError = null;
  try { progress = JSON.parse(fs.readFileSync(path.join(dir, 'progress.json'), 'utf8')); } catch (e) { progressError = e.code === 'ENOENT' ? 'missing' : 'invalid JSON'; }
  let handoff = null;
  try { handoff = fs.readFileSync(path.join(dir, 'docs/handoff/next-session.md'), 'utf8'); } catch { /* missing */ }

  const counts = git(dir, 'rev-list', '--left-right', '--count', '@{upstream}...HEAD');
  const [behind, ahead] = counts ? counts.split(/\s+/).map(Number) : [];
  const status = git(dir, 'status', '--porcelain') ?? '';

  process.stdout.write(buildBriefing({
    source: input.source,
    branch: git(dir, 'branch', '--show-current'),
    head: git(dir, 'log', '-1', '--format=%h %s'),
    dirty: status.split('\n').filter(Boolean).map((l) => l.slice(3)),
    aheadBehind: counts ? `${ahead} ahead, ${behind} behind` : null,
    progress, progressError, handoff,
    commitsSinceHandoff: (() => {
      const sha = git(dir, 'log', '-1', '--format=%H', '--', 'docs/handoff/next-session.md');
      return sha ? Number(git(dir, 'rev-list', '--count', '--no-merges', `${sha}..HEAD`)) || 0 : 0;
    })(),
  }));
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
